struct ManagedImportIdentity<'a> {
    schema_version: u16,
    conversation_id: &'a str,
    expected_epoch: u64,
    expected_revision: u64,
    #[serde(skip_serializing_if = "Option::is_none")]
    generation_id: Option<&'a str>,
    messages: &'a [StoredMessage],
}

