#[derive(Serialize)]
struct ProjectionPayloadIdentity<'a> {
    schema_version: u16,
    conversation_id: &'a str,
    conversation_epoch: u64,
    generation_id: &'a str,
    items: &'a [TranscriptProjectionItem],
}

