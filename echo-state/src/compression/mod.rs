        let remaining = context
            .messages()
            .iter()
            .map(serde_json::to_value)
            .collect::<std::result::Result<Vec<_>, _>>()?;
        assert!(
            remaining.contains(&expected),
            "原始 Parts 字段与图片应完整保留"
        );
