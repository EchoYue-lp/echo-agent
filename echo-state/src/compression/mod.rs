const PROJECTION_ENVELOPE_PREFIX: &str = CONTEXT_PROJECTION_ENVELOPE_PREFIX;

/// Return whether a message carries the framework-owned context projection envelope.
///
/// Consumers should use this predicate instead of matching the private envelope
/// representation directly.
pub fn is_context_projection_message(message: &Message) -> bool {
    echo_core::compression::context_projection_envelope(message).is_some()
}

/// Context generated by the framework is model-visible, not source evidence.
pub fn is_generated_context_message(message: &Message) -> bool {
    echo_core::compression::is_generated_context_message(message)
}

fn projection_envelope(message: &Message) -> Option<ContextProjectionEnvelope<'_>> {
    echo_core::compression::context_projection_envelope(message)
}

fn projection_has_marker(message: &Message, marker: &str) -> bool {
    projection_envelope(message).is_some_and(|header| header.marker().as_deref() == Some(marker))
}

/// 给投影消息加上框架信封；`version: Some` 表示追加式版本投影。
fn wrap_projection_message(mut message: Message, marker: &str, version: Option<&str>) -> Message {
    let encoded_marker =
        serde_json::to_string(marker).unwrap_or_else(|_| "\"invalid-marker\"".to_string());
    let envelope = match version {
        Some(version) => format!(
            "{PROJECTION_ENVELOPE_PREFIX}\nmarker={encoded_marker}\nplacement=tail\nversion={}\n\n",
            serde_json::to_string(version).unwrap_or_else(|_| "\"invalid-version\"".to_string())
        ),
        None => {
            format!("{PROJECTION_ENVELOPE_PREFIX}\nmarker={encoded_marker}\nplacement=boundary\n\n")
        }
    };
    let envelope = if version.is_some() {
        format!(
            "{envelope}Generated runtime snapshot: the latest snapshot with this marker supersedes earlier snapshots of the same source. Original user requests and authoritative instructions retain their meaning.\n"
        )
    } else {
        envelope
    };
    match &mut message.content {
        MessageContent::Text(content) => {
            *content = format!("{envelope}{content}");
        }
        MessageContent::Parts(parts) => {
            parts.insert(0, ContentPart::Text { text: envelope });
        }
        MessageContent::Empty => {
            message.content = MessageContent::Text(envelope);
        }
    }
    message
}

/// Callback trait for promoting evicted messages to long-term memory.
///
/// When compression evicts messages from the context, this trait allows
/// extracting key facts and writing them to a memory Store for later recall.
/// This is the "L3 Memory Promotion" mechanism.
pub trait MemoryPromoter: Send + Sync {
    /// Process evicted messages and promote key facts to memory.
    fn promote(
        &self,
        evicted: &[Message],
    ) -> futures::future::BoxFuture<'_, Result<MemoryPromotionReceipt>>;
}

/// Durable outcome of one memory-promotion attempt.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct MemoryPromotionReceipt {
    pub submitted: usize,
    pub promoted: usize,
    pub deduplicated: usize,
}

/// Blanket implementation for `Arc<dyn MemoryPromoter>`.
impl MemoryPromoter for Arc<dyn MemoryPromoter> {
    fn promote(
        &self,
        evicted: &[Message],
    ) -> futures::future::BoxFuture<'_, Result<MemoryPromotionReceipt>> {
        (**self).promote(evicted)
    }
}

