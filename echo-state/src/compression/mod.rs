    #[test]
    fn boundary_projection_parts_body_keeps_identity() -> Result<()> {
        let mut context = ContextManager::builder(4096).build();
        let body = Message::user_with_image("version=\"x\"\n配置事实🚀", "image/png", "AAAA");
        let original = serde_json::to_value(&body.content)?;
        context.apply_projections(&[ContextProjection::replacing("config", Some(body))]);
        let message = context.messages().first().ok_or_else(|| {
            echo_core::error::ReactError::Other("missing boundary projection".into())
        })?;
        assert!(is_context_projection_message(message));
        assert!(projection_envelope(message).is_some_and(|header| !header.is_append_version()));
        let mut restored = message.content.clone();
        if let MessageContent::Parts(parts) = &mut restored
            && !parts.is_empty()
        {
            parts.remove(0);
        }
        assert_eq!(serde_json::to_value(restored)?, original);
        Ok(())
    }

